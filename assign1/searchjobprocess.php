            <?php
            require 'sanitiseInput.php';

            $filePath = '../../data/jobposts/jobs.txt';

            function convertToDate($date)
            {
                $date = explode('/', $date);
                return strtotime("20" . $date[2] . '/' . $date[1] . '/' . $date[0]);
            }
            function validateCheckbox($value)
            {
                if (isset($value)) {
                    return sanitiseInput(implode(', ', $value));
                } else {
                    return false;

                }
            }

            function compareClosingDates($a, $b) {
                $closingDateA = convertToDate($a[3]); // Assuming closing date is at index 3
                $closingDateB = convertToDate($b[3]); // Assuming closing date is at index 3

                // Compare the closing dates
                if ($closingDateA == $closingDateB) {
                    return 0;
                }
                return ($closingDateA > $closingDateB) ? -1 : 1;
            }
            function validateLocation($value)
            {
                if ($value !== 'none') {
                    return $value;
                } else {
                    return false;
                }
            }

            if (isset($_GET['jobTitle']) && !empty($_GET['jobTitle'])) {
                $jobTitle = strtolower(sanitiseInput($_GET['jobTitle']));
                $position = isset($_GET['position']) ? $_GET['position'] : false;
                $contract = isset($_GET['contract']) ? $_GET['contract'] : false;
                $application = isset($_GET['application']) ? validateCheckbox($_GET['application']) : false;
                $location = isset($_GET['location']) ? validateLocation($_GET['location']) : false;

                if (!file_exists($filePath)) {
                    echo "<p style='color: red'>No job posts found (file doesn't exist).</p>";
                } else {
                    $handle = fopen($filePath, 'r');
                    $result = array();
                    echo "<div class='flex flex-wrap justify-center items-center'>";
                    while (($line = fgets($handle)) !== false) {
                        $attributes = explode("\t", $line);
                        if ((isset($attributes[0]) && strpos(strtolower($attributes[0]), $jobTitle) !== false) && //using isset in case the field jobtitle is broken
                            (!$position || strpos($attributes[4], $position) !== false) &&
                            (!$contract || strpos($attributes[5], $contract) !== false) &&
                            (!$application || strpos($attributes[6], $application) !== false) &&
                            (!$location || strpos($attributes[7], $location) !== false) &&
                            (convertToDate($attributes[3]) >= time()))
                        {
                            $result[] = $attributes;

                        }
                    }
                    if (empty($result)) {
                        echo "<p style='color: red' class='my-2'>No job posts found.</p>";
                    } else {
                        usort($result, 'compareClosingDates');
                        foreach ($result as $job) {
                            echo "<div class='bg-gray-50 bg-opacity-30 border border-black border-opacity-20 p-3 md:p-7 rounded-lg shadow-md m-4 transition transform duration-150 hover:bg-opacity-30 hover:-translate-y-1 hover:shadow-lg setminwidth'>";
                            echo "<p class=' '><strong>Title: </strong>" . $job[0] . "</p>";
                            echo "<p class=' '><strong>Position ID: </strong>" . $job[1] . "</p>";
                            echo "<p class=''><strong>Description: </strong>" . $job[2] . "</p>";
                            echo "<p class=' '><strong>Closing Date: </strong>" . $job[3] . "</p>";
                            echo "<p class=' '><strong>Position: </strong>" . $job[4] . "</p>";
                            echo "<p class=' '><strong>Contract: </strong>" . $job[5] . "</p>";
                            echo "<p class=' '><strong>Application by: </strong>" . $job[6] . "</p>";
                            echo "<p class=' '><strong>Location: </strong>" . $job[7] . "</p>";
                            echo "</div>";
                        }
                    }

                    echo "</div>";
                    fclose($handle);


                }
            } else {
                echo "<p style='color: red'>Please provide the job title.</p>";
            }
